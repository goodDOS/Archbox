export const S2T = new Map();
for (let i = 0; i + 1 < S2T_CHARS.length; i += 2) S2T.set(S2T_CHARS[i], S2T_CHARS[i + 1]);

const PHRASES = Object.entries(S2T_PHRASES).sort((a, b) => b[0].length - a[0].length);

/** 简体串 → 繁体串（只转字形，不改用词）
 *
 * 不能用「逐个词组做 split/join」：位置的先后会让长词被短词抢先切碎
 * （「恢复写入」里的「复写」会先命中「複寫」，剩下「恢複寫入」）。
 * 改为从左到右扫描，每个位置取**最长**的匹配词，没有再退化为单字。
 */
export function toTw(s) {
  const chars = [...s];
  const maxLen = Math.max(...PHRASES.map(([k]) => [...k].length), 1);
  let i = 0;
  let out = '';
  while (i < chars.length) {
    let hit = null;
    for (let n = Math.min(maxLen, chars.length - i); n >= 1; n--) {
      const seg = chars.slice(i, i + n).join('');
      const t = S2T_PHRASES[seg];
      if (t) {
        hit = { t, n };
        break;
      }
    }
    if (hit) {
      out += hit.t;
      i += hit.n;
    } else {
      out += S2T.get(chars[i]) || chars[i];
      i += 1;
    }
  }
  return out;
}
